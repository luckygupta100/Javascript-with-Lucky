// Logical Operator
// AND-->all condition must be true.

const age =20;
const gender = 'Male';

if(age >= 18 && gender == 'Male'){
    console.log('You are adult male')
}
// OR --> at least one condition true 
const ag =20;
const gende = 'Male';

if(ag >= 18 | gende  == 'Male'){
    console.log('You are adult male')
}